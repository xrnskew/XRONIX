def slot_sphere(slot: str):
    sp = slot.rsplit("_", 1)[0]
    return sp if sp in SPHERES and slot.endswith(("_tip", "_risk")) else None


MIN_VARIANTS, MAX_VARIANTS = 5, 15
_INFORMAL = re.compile(r"(?<![а-яё])(ты|тебе|тебя|твой|твоя|твои|твоё|твое|хочешь|можешь|напиши|скажи|давай|здравствуй|"
                       r"хай)(?![а-яё])", re.I)


def check_contract(text: str) -> list:
    """Ровно правила checkPhrases из contracts/check.mjs."""
    e = []
    for name in re.findall(r"\{([^}]*)\}", text):
        if name not in PLACEHOLDERS:
            e.append(f"неизвестная подстановка {{{name}}}")
    if re.search(r"[{}]", re.sub(r"\{[a-z_]+\}", "", text)):
        e.append("непарная фигурная скобка")
    if re.search(r"одобр|гарантир", text, re.I):
        e.append("обещание кредита запрещено (ai.md, правило 7)")
    return e


def check_variant(slot: str, text: str) -> list:
    """Все автоматические проверки варианта. Пустой список — вариант годится для вычитки."""
    _, _, required, allowed, question = SLOTS[slot]
    e = check_contract(text)
    used = set(re.findall(r"\{([a-z_]+)\}", text))
    if re.search(r"\d", text):
        e.append("цифры: числа только через подстановки")
    if used - allowed:
        e.append(f"подстановки не для этого слота: {sorted(used - allowed)}")
    if required - used:
        e.append(f"нет обязательных подстановок: {sorted(required - used)}")
    if re.search(r"(около|примерно|приблизительно)\s+\{venues\}", text, re.I):
        e.append("«около» перед {venues}: оно уже в подстановке")
    limit = 160 if question else 300
    if not 10 <= len(text) <= limit:
        e.append(f"длина {len(text)}, нужно 10–{limit}")
    if question and "?" not in text:
        e.append("это должен быть вопрос со знаком «?»")
    if re.search(r"(?<![а-яё])(в|во|городе|города|город)\s+\{in_city\}", text, re.I):
        e.append("перед {in_city} лишнее «в»/«город»: подстановка уже «в Самаре»")
    if re.search(r"(?<![а-яё])(в|сфере|области|сферы|области)\s+\{sphere\}", text, re.I):
        e.append("{sphere} в именительном («пекарня»): «в сфере {sphere}» не склоняется")
    # «Росстата» склоняется, поэтому для зарплаты — только «по данным {source}». В конкуренции источник — OpenStreetMap,
    # он не склоняется, и там годится любое место.
    if slot == "salary_fact" and not re.search(r"(данным|данных|сведениям|сведений|информации|статистик[аи]|источника|"
                                            r"подсчётам|подсчетам)\s+\{source\}|\(\{source\}\)", text):
        e.append("{source} в родительном падеже: «по данным {source}»")
    if _INFORMAL.search(text):
        e.append("обращение на «ты»: нужно на «вы»")
    if re.search(r"[a-z]{3,}", re.sub(r"\{[a-z_]+\}|OpenStreetMap", "", text)):
        e.append("латиница в тексте")
    if re.search(r"(?<![а-яё])(точно дадут|выдадут|откажут|не дадут)(?![а-яё])", text, re.I):
        e.append("обещание или отказ в кредите")
    return e
